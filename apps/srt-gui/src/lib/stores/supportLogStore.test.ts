import { expect, it, vi } from "vitest";
vi.mock("@tauri-apps/api/core", () => ({ invoke: vi.fn() }));
vi.mock("@tauri-apps/api/event", () => ({ listen: vi.fn(async () => () => {}) }));
import { invoke } from "@tauri-apps/api/core";
import { listen } from "@tauri-apps/api/event";
import { SupportLogStore } from "./supportLogStore.svelte";
import { recordSupportEvent } from "$lib/utils/supportLog";
it("flushes the complete log snapshot before export and persists before stop", async () => {
  const store = new SupportLogStore();
  vi.mocked(invoke).mockImplementation(async command => command === "support_log_start" ? "/tmp/session.jsonl" : command === "support_log_export" ? "/tmp/export.jsonl" : { path: null, recording: false });
  recordSupportEvent("test", "before recording");
  await Promise.resolve();
  expect(store.previewText).toContain("before recording");
  expect(invoke).not.toHaveBeenCalled();
  await store.start(); expect(store.recording).toBe(true);
  expect(store.previewText).toContain("before recording");
  for (let i = 0; i < 1250; i++) recordSupportEvent("test", `entry-${i}`);
  await Promise.resolve();
  expect(store.preview).toHaveLength(200);
  expect(store.preview[0].message).toBe("entry-1050");
  expect(store.previewText).toContain("entry-1249");
  await store.export("/tmp/export.jsonl");
  expect(store.preview).toHaveLength(200);
  const exportedCalls = vi.mocked(invoke).mock.calls;
  const exportIndex = exportedCalls.findIndex(([command]) => command === "support_log_export");
  const batches = exportedCalls.slice(0, exportIndex).filter(([command]) => command === "support_log_append");
  const written = batches.flatMap(([, args]) => (args as { entries: string[] }).entries.map(entry => JSON.parse(entry).message));
  expect(written).toEqual(["Recording enabled", ...Array.from({ length: 1250 }, (_, index) => `entry-${index}`)]);
  recordSupportEvent("test", "last entry"); await store.stop();
  expect(store.recording).toBe(false);
  expect(invoke).toHaveBeenLastCalledWith("support_log_stop");
  expect(store.path).toBe("/tmp/session.jsonl");
  recordSupportEvent("test", "after recording");
  await Promise.resolve();
  expect(store.previewText).toContain("after recording");
  expect(invoke).toHaveBeenLastCalledWith("support_log_stop");
});

it("records retry metadata without copying unexpected provider payload fields", async () => {
  const store = new SupportLogStore();
  vi.mocked(invoke).mockClear();
  vi.mocked(listen).mockClear();
  vi.mocked(invoke).mockImplementation(async command => command === "support_log_start" ? "/tmp/session.jsonl" : { path: null, recording: false });
  let emitRetry = () => {};
  vi.mocked(listen).mockImplementation(async (name, callback) => {
    if (name === "provider-retry") emitRetry = () => callback({ event: name, id: 0, payload: { tier: 1, endpoint: 2, status: 429, attempt: 1, max_retries: 3, retry_in_ms: 3000, body: "PRIVATE-SUBTITLE", api_key: "private-key" } } as never);
    return () => {};
  });
  await store.initialize();
  emitRetry();
  await Promise.resolve();
  expect(store.previewText).toContain("provider-retry");
  expect(invoke).not.toHaveBeenCalledWith("support_log_append", expect.anything());
  const registrationCount = vi.mocked(listen).mock.calls.length;
  await store.start();
  emitRetry();
  await store.stop();
  expect(listen).toHaveBeenCalledTimes(registrationCount);
  const entries = vi.mocked(invoke).mock.calls.filter(([command]) => command === "support_log_append")
    .flatMap(([, args]) => (args as { entries: string[] }).entries).map(entry => JSON.parse(entry));
  const retry = entries.find(entry => entry.kind === "provider-retry");
  expect(JSON.parse(retry.message)).toEqual({ tier: 1, endpoint: 2, status: 429, attempt: 1, max_retries: 3, retry_in_ms: 3000 });
  expect(JSON.stringify(entries)).not.toMatch(/PRIVATE-SUBTITLE|private-key/);
  expect(store.previewText).not.toMatch(/PRIVATE-SUBTITLE|private-key/);
  expect(store.previewText).toContain("Recording stopped");
});
