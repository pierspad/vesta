use crate::export_tsv::sanitize_filename;
use crate::{FlashcardConfig, MatchedLine, build_matched_lines};
use serde::{Deserialize, Serialize};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn default_true() -> bool {
    true
}

/// Output container format for bilingual "dueling" subtitles.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum DuelingFormat {
    /// Advanced SubStation Alpha (`.ass`) with separate `Subs1` (bottom) and `Subs2` (top) styles.
    #[default]
    Ass,
    /// SubRip (`.srt`) with both tracks stacked inside each cue.
    Srt,
}

impl DuelingFormat {
    pub fn extension(self) -> &'static str {
        match self {
            Self::Ass => "ass",
            Self::Srt => "srt",
        }
    }
}

/// Options controlling bilingual dueling subtitle export.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DuelingExportOptions {
    #[serde(default)]
    pub format: DuelingFormat,
    /// Explicit destination file path. When omitted, writes `<output_dir>/<deck>.dueling.<ext>`.
    #[serde(default)]
    pub output_path: Option<String>,
    /// Put the target track first (bottom in ASS / first line in SRT). When false, native comes first.
    #[serde(default = "default_true")]
    pub target_first: bool,
    /// Keep active target lines that do not have a matching native subtitle.
    #[serde(default = "default_true")]
    pub include_unmatched: bool,
}

impl Default for DuelingExportOptions {
    fn default() -> Self {
        Self {
            format: DuelingFormat::Ass,
            output_path: None,
            target_first: true,
            include_unmatched: true,
        }
    }
}

/// Summary returned after writing a dueling subtitle file.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DuelingResult {
    pub output_path: String,
    pub format: DuelingFormat,
    pub line_count: usize,
    pub matched_count: usize,
}

fn ms_to_ass_ts(ms: i64) -> String {
    let clamped = ms.max(0);
    let total_cs = clamped / 10;
    let cs = total_cs % 100;
    let total_secs = total_cs / 100;
    let secs = total_secs % 60;
    let total_mins = total_secs / 60;
    let mins = total_mins % 60;
    let hours = total_mins / 60;
    format!("{hours}:{mins:02}:{secs:02}.{cs:02}")
}

fn ms_to_srt_ts(ms: i64) -> String {
    let clamped = ms.max(0);
    let millis = clamped % 1000;
    let total_secs = clamped / 1000;
    let secs = total_secs % 60;
    let total_mins = total_secs / 60;
    let mins = total_mins % 60;
    let hours = total_mins / 60;
    format!("{hours:02}:{mins:02}:{secs:02},{millis:03}")
}

fn escape_ass_text(text: &str) -> String {
    text.trim()
        .replace("\r\n", "\n")
        .replace('\r', "\n")
        .replace('\n', "\\N")
}

fn normalize_srt_text(text: &str) -> String {
    text.trim().replace("\r\n", "\n").replace('\r', "\n")
}

fn collect_dueling_rows(
    lines: &[MatchedLine],
    include_unmatched: bool,
) -> Vec<(&MatchedLine, Option<&str>)> {
    lines
        .iter()
        .filter(|line| line.active && !line.subs1.text.trim().is_empty())
        .filter_map(|line| {
            let native = line
                .subs2
                .as_ref()
                .map(|sub| sub.text.trim())
                .filter(|text| !text.is_empty());
            if !include_unmatched && native.is_none() {
                return None;
            }
            Some((line, native))
        })
        .collect()
}

/// Format matched subtitle pairs into `.ass` or `.srt` content without performing file I/O.
pub fn format_dueling_subtitles(
    lines: &[MatchedLine],
    title: &str,
    options: &DuelingExportOptions,
) -> String {
    let rows = collect_dueling_rows(lines, options.include_unmatched);
    let safe_title = title.trim();
    let header_title = if safe_title.is_empty() {
        "Vesta Dueling Subtitles"
    } else {
        safe_title
    };

    match options.format {
        DuelingFormat::Ass => {
            let (subs1_align, subs1_margin_v, subs2_align, subs2_margin_v) = if options.target_first
            {
                (2, 36, 8, 30)
            } else {
                (8, 30, 2, 36)
            };

            let mut out = String::with_capacity(rows.len() * 140 + 512);
            let _ = writeln!(out, "; Generated by Vesta");
            let _ = writeln!(out, "[Script Info]");
            let _ = writeln!(out, "Title: {}", header_title.replace(['\r', '\n'], " "));
            let _ = writeln!(out, "ScriptType: v4.00+");
            let _ = writeln!(out, "PlayResX: 1920");
            let _ = writeln!(out, "PlayResY: 1080");
            let _ = writeln!(out, "WrapStyle: 0");
            let _ = writeln!(out, "ScaledBorderAndShadow: yes");
            let _ = writeln!(out, "Collisions: Normal");
            let _ = writeln!(out);
            let _ = writeln!(out, "[V4+ Styles]");
            let _ = writeln!(
                out,
                "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding"
            );
            let _ = writeln!(
                out,
                "Style: Subs1,Arial,54,&H00FFFFFF,&H0000FFFF,&H0010141C,&H80000000,0,0,0,0,100,100,0,0,1,3,1,{subs1_align},48,48,{subs1_margin_v},1"
            );
            let _ = writeln!(
                out,
                "Style: Subs2,Arial,46,&H00A8E8FF,&H0000FFFF,&H0010141C,&H80000000,0,0,0,0,100,100,0,0,1,2.5,1,{subs2_align},48,48,{subs2_margin_v},1"
            );
            let _ = writeln!(out);
            let _ = writeln!(out, "[Events]");
            let _ = writeln!(
                out,
                "Format: Layer, Start, End, Style, Actor, MarginL, MarginR, MarginV, Effect, Text"
            );

            for (line, native) in rows {
                let start = line.subs1.start_ms.max(0);
                let end = line.subs1.end_ms.max(start);
                let start_ts = ms_to_ass_ts(start);
                let end_ts = ms_to_ass_ts(end);
                let primary = escape_ass_text(&line.subs1.text);

                if options.target_first {
                    let _ = writeln!(
                        out,
                        "Dialogue: 0,{start_ts},{end_ts},Subs1,,0,0,0,,{primary}"
                    );
                    if let Some(nat) = native {
                        let secondary = escape_ass_text(nat);
                        let _ = writeln!(
                            out,
                            "Dialogue: 0,{start_ts},{end_ts},Subs2,,0,0,0,,{secondary}"
                        );
                    }
                } else {
                    if let Some(nat) = native {
                        let secondary = escape_ass_text(nat);
                        let _ = writeln!(
                            out,
                            "Dialogue: 0,{start_ts},{end_ts},Subs2,,0,0,0,,{secondary}"
                        );
                    }
                    let _ = writeln!(
                        out,
                        "Dialogue: 0,{start_ts},{end_ts},Subs1,,0,0,0,,{primary}"
                    );
                }
            }
            out
        }
        DuelingFormat::Srt => {
            let mut out = String::with_capacity(rows.len() * 120);
            for (idx, (line, native)) in rows.into_iter().enumerate() {
                let start = line.subs1.start_ms.max(0);
                let end = line.subs1.end_ms.max(start);
                let start_ts = ms_to_srt_ts(start);
                let end_ts = ms_to_srt_ts(end);
                let primary = normalize_srt_text(&line.subs1.text);

                if idx > 0 {
                    out.push('\n');
                }
                let _ = writeln!(out, "{}", idx + 1);
                let _ = writeln!(out, "{start_ts} --> {end_ts}");
                match native {
                    Some(nat) => {
                        let secondary = normalize_srt_text(nat);
                        if options.target_first {
                            let _ = writeln!(out, "{primary}");
                            let _ = writeln!(out, "{secondary}");
                        } else {
                            let _ = writeln!(out, "{secondary}");
                            let _ = writeln!(out, "{primary}");
                        }
                    }
                    None => {
                        let _ = writeln!(out, "{primary}");
                    }
                }
            }
            out
        }
    }
}

fn resolve_dueling_output_path(
    config: &FlashcardConfig,
    options: &DuelingExportOptions,
) -> Result<PathBuf, String> {
    if let Some(explicit) = options
        .output_path
        .as_deref()
        .map(str::trim)
        .filter(|path| !path.is_empty())
    {
        return Ok(PathBuf::from(explicit));
    }

    let base_dir = if !config.output_dir.trim().is_empty() {
        PathBuf::from(config.output_dir.trim())
    } else {
        match Path::new(&config.target_subs_path).parent() {
            Some(parent) if !parent.as_os_str().is_empty() => parent.to_path_buf(),
            Some(_) => PathBuf::from("."),
            None => {
                return Err("Output directory is required for dueling subtitle export".to_string());
            }
        }
    };

    let raw_name = if !config.deck_name.trim().is_empty() {
        config.deck_name.trim().to_string()
    } else {
        Path::new(&config.target_subs_path)
            .file_stem()
            .and_then(|stem| stem.to_str())
            .unwrap_or("dueling")
            .to_string()
    };
    let sanitized = sanitize_filename(&raw_name);
    let stem = if sanitized.is_empty() {
        "dueling".to_string()
    } else {
        sanitized
    };

    Ok(base_dir.join(format!("{stem}.dueling.{}", options.format.extension())))
}

/// Run the shared subtitle pipeline (`parse -> shift -> match -> span -> filter -> combine`)
/// and atomically export a bilingual `.ass` or `.srt` file.
pub fn export_dueling_subtitles(
    config: &FlashcardConfig,
    options: DuelingExportOptions,
) -> Result<DuelingResult, String> {
    if config.target_subs_path.trim().is_empty() {
        return Err("Target subtitle path is required".to_string());
    }
    let matched = build_matched_lines(config)?;
    let rows = collect_dueling_rows(&matched, options.include_unmatched);
    if rows.is_empty() {
        return Err("No active subtitle lines match the current settings".to_string());
    }

    let line_count = rows.len();
    let matched_count = rows.iter().filter(|(_, native)| native.is_some()).count();

    let title = if !config.deck_name.trim().is_empty() {
        config.deck_name.as_str()
    } else {
        Path::new(&config.target_subs_path)
            .file_stem()
            .and_then(|stem| stem.to_str())
            .unwrap_or("Vesta Dueling Subtitles")
    };

    let content = format_dueling_subtitles(&matched, title, &options);
    let output_path = resolve_dueling_output_path(config, &options)?;

    if let Some(parent) = output_path.parent().filter(|p| !p.as_os_str().is_empty()) {
        std::fs::create_dir_all(parent).map_err(|e| {
            format!(
                "Failed to create output directory {}: {e}",
                parent.display()
            )
        })?;
    }

    srt_parser::persistence::atomic_write_with(&output_path, |file| {
        use std::io::Write as _;
        file.write_all(content.as_bytes())?;
        Ok(())
    })
    .map_err(|e| format!("Failed to write dueling subtitles: {e}"))?;

    Ok(DuelingResult {
        output_path: output_path.to_string_lossy().into_owned(),
        format: options.format,
        line_count,
        matched_count,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{SubEntry, SubtitleFilters, parse_subtitle_file};

    fn sample_lines() -> Vec<MatchedLine> {
        vec![
            MatchedLine {
                index: 0,
                subs1: SubEntry {
                    id: 1,
                    start_ms: 1000,
                    end_ms: 3500,
                    text: "こんにちは\n世界".into(),
                    actor: None,
                    style: None,
                    active: true,
                },
                subs2: Some(SubEntry {
                    id: 1,
                    start_ms: 1000,
                    end_ms: 3500,
                    text: "Hello world".into(),
                    actor: None,
                    style: None,
                    active: true,
                }),
                active: true,
                leading_context: vec![],
                trailing_context: vec![],
            },
            MatchedLine {
                index: 1,
                subs1: SubEntry {
                    id: 2,
                    start_ms: 4000,
                    end_ms: 5200,
                    text: "Filtered out".into(),
                    actor: None,
                    style: None,
                    active: false,
                },
                subs2: None,
                active: false,
                leading_context: vec![],
                trailing_context: vec![],
            },
            MatchedLine {
                index: 2,
                subs1: SubEntry {
                    id: 3,
                    start_ms: 6000,
                    end_ms: 7500,
                    text: "Solo target".into(),
                    actor: None,
                    style: None,
                    active: true,
                },
                subs2: None,
                active: true,
                leading_context: vec![],
                trailing_context: vec![],
            },
        ]
    }

    #[test]
    fn formats_ass_with_distinct_styles_and_line_breaks() {
        let content = format_dueling_subtitles(
            &sample_lines(),
            "Episode 1",
            &DuelingExportOptions::default(),
        );
        assert!(content.contains("Style: Subs1,"));
        assert!(content.contains("Style: Subs2,"));
        assert!(
            content.contains("Dialogue: 0,0:00:01.00,0:00:03.50,Subs1,,0,0,0,,こんにちは\\N世界")
        );
        assert!(content.contains("Dialogue: 0,0:00:01.00,0:00:03.50,Subs2,,0,0,0,,Hello world"));
        assert!(content.contains("Solo target"));
        assert!(!content.contains("Filtered out"));
    }

    #[test]
    fn formats_srt_respecting_order_and_unmatched_option() {
        let content = format_dueling_subtitles(
            &sample_lines(),
            "Episode 1",
            &DuelingExportOptions {
                format: DuelingFormat::Srt,
                output_path: None,
                target_first: false,
                include_unmatched: false,
            },
        );
        assert!(content.contains("00:00:01,000 --> 00:00:03,500\nHello world\nこんにちは\n世界"));
        assert!(!content.contains("Solo target"));
    }

    #[test]
    fn exports_dueling_ass_and_srt_files_atomically_and_roundtrips() {
        let dir = tempfile::tempdir().unwrap();
        let target = dir.path().join("ja.srt");
        let native = dir.path().join("en.srt");
        std::fs::write(
            &target,
            "1\n00:00:01,000 --> 00:00:03,000\nおはよう\n\n2\n00:00:04,000 --> 00:00:05,000\nじゃあね\n",
        )
        .unwrap();
        std::fs::write(&native, "1\n00:00:01,100 --> 00:00:02,900\nGood morning\n").unwrap();

        let config = FlashcardConfig {
            target_subs_path: target.to_string_lossy().into_owned(),
            native_subs_path: Some(native.to_string_lossy().into_owned()),
            output_dir: dir.path().to_string_lossy().into_owned(),
            deck_name: "My Show / Ep 01".into(),
            filters: SubtitleFilters::default(),
            ..FlashcardConfig::default()
        };

        let ass_res = export_dueling_subtitles(&config, DuelingExportOptions::default()).unwrap();
        assert_eq!(ass_res.line_count, 2);
        assert_eq!(ass_res.matched_count, 1);
        assert!(ass_res.output_path.ends_with("My_Show___Ep_01.dueling.ass"));
        let (parsed_ass, fmt) = parse_subtitle_file(&ass_res.output_path).unwrap();
        assert_eq!(fmt, "ass");
        assert_eq!(parsed_ass.len(), 3);

        let srt_out = dir.path().join("custom.srt");
        let srt_res = export_dueling_subtitles(
            &config,
            DuelingExportOptions {
                format: DuelingFormat::Srt,
                output_path: Some(srt_out.to_string_lossy().into_owned()),
                target_first: true,
                include_unmatched: false,
            },
        )
        .unwrap();
        assert_eq!(srt_res.line_count, 1);
        assert_eq!(srt_res.matched_count, 1);
        let (parsed_srt, fmt) = parse_subtitle_file(&srt_res.output_path).unwrap();
        assert_eq!(fmt, "srt");
        assert_eq!(parsed_srt.len(), 1);
        assert!(parsed_srt[0].text.contains("おはよう\nGood morning"));
    }
}
